end $$;

-- ---------------------------------------------------------------------
-- 3. Textos legíveis para o histórico
-- ---------------------------------------------------------------------
create or replace function public.fmt_dt(ts timestamptz)
returns text language sql stable set search_path = public as $$
  select case when ts is null then '(sem data)' else to_char(ts at time zone 'America/Campo_Grande', 'DD/MM/YYYY HH24:MI') end;
$$;

create or replace function public.fmt_brl(v numeric)
returns text language sql immutable set search_path = public as $$
  select case when v is null then '(sem valor)' else 'R$ ' || translate(to_char(v, 'FM999,999,999,990.00'), ',.', '.,') end;
$$;

create or replace function public.interaction_type_label(t text)
returns text language sql immutable set search_path = public as $$
  select case t when 'visita' then 'visita' when 'ligacao' then 'ligação' when 'reuniao' then 'reunião' else 'contato' end;
$$;

-- "label: antes → depois" (ou null se não mudou)
create or replace function public.audit_diff(label text, a text, b text)
returns text language sql immutable set search_path = public as $$
  select case when a is distinct from b
    then label || ': ' || coalesce(nullif(a, ''), '(vazio)') || ' → ' || coalesce(nullif(b, ''), '(vazio)')
  end;
$$;

create or replace function public.person_name(p_id uuid)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select coalesce(nullif(trim(full_name), ''), email) from public.profiles where id = p_id), '(ninguém)');
$$;

create or replace function public.store_name(p_id uuid)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select name from public.stores where id = p_id), 'Sem loja');
$$;

-- Nome legível de um registro (inclusive já excluído)
create or replace function public.entity_label(p_type text, p_id uuid)
returns text language plpgsql stable security definer set search_path = public as $$
declare v text;
begin
  if p_type = 'client' then
    select 'cliente "' || name || '"' into v from public.clients where id = p_id;
  elsif p_type = 'interaction' then
    select public.interaction_type_label(i.type) || ' de ' || public.fmt_dt(i.happened_at) || ' do cliente "' || c.name || '"'
      into v from public.interactions i join public.clients c on c.id = i.client_id where i.id = p_id;
  elsif p_type = 'sale' then
    select 'venda de ' || public.fmt_brl(s.amount) || ' (' || to_char(s.sold_at at time zone 'America/Campo_Grande', 'DD/MM/YYYY') || ') do cliente "' || c.name || '"'
      into v from public.sales s join public.clients c on c.id = s.client_id where s.id = p_id;
  end if;
  return coalesce(v, 'registro ' || p_id::text);
end;
$$;

-- ---------------------------------------------------------------------
-- 4. Auditoria automática (gatilhos) — ninguém consegue "pular" o registro
-- ---------------------------------------------------------------------
create or replace function public.audit_clients()
returns trigger language plpgsql security definer set search_path = public as $$
declare v text;
begin
  if tg_op = 'INSERT' then
    perform public.log_activity('CRIOU', 'client', new.id,
      'Cadastrou o cliente "' || new.name || '" (loja ' || public.store_name(new.store_id) || ', vendedor ' || public.person_name(new.user_id) || ')');
    return new;
  end if;
  if old.deleted_at is distinct from new.deleted_at then
    return new; -- exclusão é registrada pelo fluxo de exclusão
  end if;
  v := array_to_string(array[
    public.audit_diff('nome', old.name, new.name),
    public.audit_diff('empresa', old.company, new.company),
    public.audit_diff('telefone', old.phone, new.phone),
    public.audit_diff('email', old.email, new.email),
    public.audit_diff('endereço', old.address, new.address),
    case when old.notes is distinct from new.notes then 'observações alteradas' end,
    case when old.user_id is distinct from new.user_id
      then public.audit_diff('vendedor responsável', public.person_name(old.user_id), public.person_name(new.user_id)) end,
    case when old.store_id is distinct from new.store_id
      then public.audit_diff('loja', public.store_name(old.store_id), public.store_name(new.store_id)) end
  ], '; ');
  if v <> '' then
    perform public.log_activity('EDITOU', 'client', new.id, 'Editou o cliente "' || new.name || '": ' || v);
  end if;
  return new;
end;
$$;

create or replace function public.audit_interactions()
returns trigger language plpgsql security definer set search_path = public as $$
declare v text; v_client text;
begin
  select name into v_client from public.clients where id = new.client_id;
  if tg_op = 'INSERT' then
    perform public.log_activity('CRIOU', 'interaction', new.id,
      'Registrou ' || public.interaction_type_label(new.type) || ' em ' || public.fmt_dt(new.happened_at) ||
      ' no cliente "' || v_client || '"' ||
      coalesce(' — retorno agendado para ' || public.fmt_dt(new.follow_up_at), ''));
    return new;
  end if;
  if old.deleted_at is distinct from new.deleted_at then
    return new;
  end if;
  v := array_to_string(array[
    public.audit_diff('tipo', public.interaction_type_label(old.type), public.interaction_type_label(new.type)),
    case when old.happened_at is distinct from new.happened_at
      then public.audit_diff('data', public.fmt_dt(old.happened_at), public.fmt_dt(new.happened_at)) end,
    public.audit_diff('com quem falou', old.contact_person, new.contact_person),
    case when old.notes is distinct from new.notes then 'anotações alteradas' end,
    case when old.follow_up_at is distinct from new.follow_up_at
      then public.audit_diff('retorno agendado',
        case when old.follow_up_at is null then '' else public.fmt_dt(old.follow_up_at) end,
        case when new.follow_up_at is null then '' else public.fmt_dt(new.follow_up_at) end) end,
    case when old.follow_up_done is distinct from new.follow_up_done
      then case when new.follow_up_done then 'retorno marcado como feito' else 'retorno reaberto' end end
  ], '; ');
  if v <> '' then
    perform public.log_activity('EDITOU', 'interaction', new.id,
      'Editou a ' || public.interaction_type_label(new.type) || ' do cliente "' || v_client || '": ' || v);
  end if;
  return new;
end;
$$;

create or replace function public.audit_sales()
returns trigger language plpgsql security definer set search_path = public as $$
declare v text; v_client text;
begin
  select name into v_client from public.clients where id = new.client_id;
  if tg_op = 'INSERT' then
    perform public.log_activity('CRIOU', 'sale', new.id,
      'Registrou venda de ' || public.fmt_brl(new.amount) || ' no cliente "' || v_client || '" — pós-venda em ' ||
      public.fmt_dt(new.post_sale_due_at) || case when new.post_sale_manual then ' (data escolhida)' else ' (automático, 3 dias)' end);
    return new;
  end if;
  if old.deleted_at is distinct from new.deleted_at then
    return new;
  end if;
  v := array_to_string(array[
    case when old.sold_at is distinct from new.sold_at
      then public.audit_diff('data da venda', public.fmt_dt(old.sold_at), public.fmt_dt(new.sold_at)) end,
    case when old.amount is distinct from new.amount
      then public.audit_diff('valor', public.fmt_brl(old.amount), public.fmt_brl(new.amount)) end,
    case when old.description is distinct from new.description then 'descrição alterada' end,
    case when old.post_sale_due_at is distinct from new.post_sale_due_at
      then public.audit_diff('data do pós-venda', public.fmt_dt(old.post_sale_due_at), public.fmt_dt(new.post_sale_due_at)) end,
    case when old.post_sale_manual is distinct from new.post_sale_manual
      then case when new.post_sale_manual then 'pós-venda com data escolhida manualmente' else 'pós-venda voltou ao automático (3 dias)' end end,
    case when old.post_sale_done_at is distinct from new.post_sale_done_at
      then case when new.post_sale_done_at is not null then 'pós-venda concluído' else 'pós-venda reaberto' end end
  ], '; ');
  if v <> '' then
    perform public.log_activity('EDITOU', 'sale', new.id, 'Editou a venda do cliente "' || v_client || '": ' || v);
  end if;
  return new;
end;
$$;

create or replace function public.audit_stores()
returns trigger language plpgsql security definer set search_path = public as $$
declare v text;
begin
  if tg_op = 'INSERT' then
    perform public.log_activity('CRIOU', 'store', new.id, 'Criou a loja "' || new.name || '"');
    return new;
  end if;
  v := array_to_string(array[
    public.audit_diff('nome', old.name, new.name),
    case when old.active is distinct from new.active then case when new.active then 'loja ativada' else 'loja desativada' end end
  ], '; ');
  if v <> '' then
    perform public.log_activity('EDITOU', 'store', new.id, 'Editou a loja "' || new.name || '": ' || v);
  end if;
  return new;
end;
$$;

create or replace function public.audit_profiles()
returns trigger language plpgsql security definer set search_path = public as $$
declare v text;
begin
  if tg_op = 'INSERT' then
    perform public.log_activity('CRIOU', 'user', new.id,
      'Nova conta: ' || coalesce(nullif(trim(new.full_name), ''), new.email) || ' (' || new.email || '), loja ' ||
      public.store_name(new.store_id) || case when new.active then ', acesso liberado' else ', aguardando liberação' end,
      new.id);
    return new;
  end if;
  v := array_to_string(array[
    public.audit_diff('nome', old.full_name, new.full_name),
    public.audit_diff('papel', old.role, new.role),
    case when old.store_id is distinct from new.store_id
      then public.audit_diff('loja', public.store_name(old.store_id), public.store_name(new.store_id)) end,
    case when old.active is distinct from new.active then case when new.active then 'acesso liberado' else 'acesso bloqueado' end end
  ], '; ');
  if v <> '' then
    perform public.log_activity('EDITOU', 'user', new.id,
      'Editou o usuário ' || coalesce(nullif(trim(new.full_name), ''), new.email) || ': ' || v);
  end if;
  return new;
end;
$$;

