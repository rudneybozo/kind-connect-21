-- Pós-venda automático: recalcula sempre que não for manual
create or replace function public.sales_post_sale_default()
returns trigger language plpgsql set search_path = public as $$
begin
  if not new.post_sale_manual then
    new.post_sale_due_at := new.sold_at + interval '3 days';
  end if;
  return new;
end;
$$;

drop trigger if exists sales_post_sale_default on public.sales;
create trigger sales_post_sale_default
  before insert or update of sold_at, post_sale_manual, post_sale_due_at on public.sales
  for each row execute function public.sales_post_sale_default();

-- ---------------------------------------------------------------------
-- 2. Histórico de Atividades (cadeia de hashes)
-- ---------------------------------------------------------------------
create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid,                -- quem fez (sem FK: o histórico sobrevive à exclusão do usuário)
  user_name text not null,     -- nome no momento da ação
  action text not null,        -- CRIOU, EDITOU, EXCLUIU, SOLICITOU_EXCLUSAO, APROVOU_EXCLUSAO, ...
  entity_type text,            -- client, interaction, sale, store, user, deletion_request
  entity_id uuid,
  description text not null,
  created_at timestamptz not null,
  previous_hash text not null, -- "GENESIS" no primeiro registro
  current_hash text not null unique
);
create index if not exists activity_logs_entity_idx on public.activity_logs(entity_type, entity_id);

-- Representação padronizada (a mesma é recalculada no navegador, em src/lib/activity.ts):
-- cada campo vira "<tamanho em bytes>:<valor>" e os campos são unidos por "|".
create or replace function public.activity_log_payload(
  p_id bigint, p_created_at timestamptz, p_user_id uuid, p_user_name text, p_action text,
  p_entity_type text, p_entity_id uuid, p_description text, p_previous_hash text
) returns text language sql stable set search_path = public as $$
  select string_agg(octet_length(f)::text || ':' || f, '|' order by n)
  from unnest(array[
    p_id::text,
    to_char(p_created_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    coalesce(p_user_id::text, ''),
    p_user_name,
    p_action,
    coalesce(p_entity_type, ''),
    coalesce(p_entity_id::text, ''),
    p_description,
    p_previous_hash
  ]) with ordinality as t(f, n);
$$;

create or replace function public.activity_log_hash(
  p_id bigint, p_created_at timestamptz, p_user_id uuid, p_user_name text, p_action text,
  p_entity_type text, p_entity_id uuid, p_description text, p_previous_hash text
) returns text language sql stable set search_path = public, extensions as $$
  select encode(extensions.digest(convert_to(public.activity_log_payload(
    p_id, p_created_at, p_user_id, p_user_name, p_action, p_entity_type, p_entity_id, p_description, p_previous_hash
  ), 'UTF8'), 'sha256'), 'hex');
$$;

-- logActivity: única porta de entrada do histórico
create or replace function public.log_activity(
  p_action text,
  p_entity_type text,
  p_entity_id uuid,
  p_description text,
  p_user_id uuid default null
) returns bigint language plpgsql security definer set search_path = public, extensions as $$
declare
  v_user uuid := coalesce(p_user_id, auth.uid());
  v_name text;
  v_prev text;
  v_id bigint;
  v_at timestamptz;
begin
  -- Fila única: duas atividades simultâneas nunca leem o mesmo "último hash".
  -- O bloqueio vale até o fim da transação.
  perform pg_advisory_xact_lock(7243115001);

  select coalesce(nullif(trim(full_name), ''), email) into v_name from public.profiles where id = v_user;
  v_name := coalesce(v_name, case when v_user is null then 'Sistema' else 'Usuário removido' end);

  select current_hash into v_prev from public.activity_logs order by id desc limit 1;
  v_prev := coalesce(v_prev, 'GENESIS');

  v_id := nextval(pg_get_serial_sequence('public.activity_logs', 'id'));
  v_at := date_trunc('milliseconds', clock_timestamp());

  insert into public.activity_logs
    (id, user_id, user_name, action, entity_type, entity_id, description, created_at, previous_hash, current_hash)
  values
    (v_id, v_user, v_name, p_action, p_entity_type, p_entity_id, p_description, v_at, v_prev,
     public.activity_log_hash(v_id, v_at, v_user, v_name, p_action, p_entity_type, p_entity_id, p_description, v_prev));
  return v_id;
end;
$$;

-- Somente inclusão: nenhuma alteração ou remoção, nem pelo dono da tabela
create or replace function public.activity_logs_block_changes()
returns trigger language plpgsql as $$
begin
  raise exception 'O Histórico de Atividades é somente inclusão: não é permitido alterar ou apagar registros';
end;
$$;

drop trigger if exists activity_logs_no_update_delete on public.activity_logs;
create trigger activity_logs_no_update_delete before update or delete on public.activity_logs
  for each row execute function public.activity_logs_block_changes();
drop trigger if exists activity_logs_no_truncate on public.activity_logs;
create trigger activity_logs_no_truncate before truncate on public.activity_logs
  for each statement execute function public.activity_logs_block_changes();

alter table public.activity_logs enable row level security;
