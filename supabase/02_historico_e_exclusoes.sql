create or replace function public.admin_delete_user(p_user_id uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
declare v_desc text;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem excluir usuários';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'Você não pode excluir a sua própria conta';
  end if;
  select 'Excluiu o usuário ' || coalesce(nullif(trim(full_name), ''), email) || ' (' || email || ') e os clientes que ainda estavam com ele'
    into v_desc from public.profiles where id = p_user_id;
  perform public.log_activity('EXCLUIU', 'user', p_user_id, coalesce(v_desc, 'Excluiu um usuário'));
  delete from auth.users where id = p_user_id;
end;
$$;

create or replace function public.admin_transfer_clients(p_from uuid, p_to uuid)
returns integer language plpgsql security definer set search_path = public as $$
declare v_count integer;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem transferir clientes';
  end if;
  update public.clients
     set user_id = p_to,
         store_id = coalesce((select store_id from public.profiles where id = p_to), store_id)
   where user_id = p_from and deleted_at is null;
  get diagnostics v_count = row_count;
  perform public.log_activity('TRANSFERIU', 'user', p_from,
    'Transferiu ' || v_count || ' cliente(s) de ' || public.person_name(p_from) || ' para ' || public.person_name(p_to));
  return v_count;
end;
$$;

