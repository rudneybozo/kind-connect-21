create table if not exists public.deletion_requests (
  id uuid primary key default gen_random_uuid(),
  entity_type text not null check (entity_type in ('client', 'interaction', 'sale')),
  entity_id uuid not null,
  client_id uuid references public.clients(id) on delete cascade,
  entity_label text not null,
  reason text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  requested_by uuid not null references auth.users(id) on delete cascade,
  requested_at timestamptz not null default now(),
  decided_by uuid references auth.users(id) on delete set null,
  decided_at timestamptz,
  decision_note text
);
create unique index if not exists deletion_requests_one_pending
  on public.deletion_requests(entity_type, entity_id) where status = 'pending';
create index if not exists deletion_requests_status_idx on public.deletion_requests(status, requested_at desc);
create index if not exists deletion_requests_client_idx on public.deletion_requests(client_id);

alter table public.deletion_requests enable row level security;
revoke all on public.deletion_requests from public, anon, authenticated;
grant select on public.deletion_requests to authenticated;
grant all on public.deletion_requests to service_role;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'deletion_requests' and policyname = 'deletion_requests_select') then
    create policy deletion_requests_select on public.deletion_requests for select to authenticated
      using (public.is_admin() or requested_by = auth.uid() or public.can_access_client(client_id));
  end if;
end $$;

-- Interno: marca como excluído (exclusão lógica)
create or replace function public.soft_delete_record(p_type text, p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_type = 'client' then
    update public.clients set deleted_at = now(), deleted_by = auth.uid() where id = p_id and deleted_at is null;
  elsif p_type = 'interaction' then
    update public.interactions set deleted_at = now(), deleted_by = auth.uid() where id = p_id and deleted_at is null;
  elsif p_type = 'sale' then
    update public.sales set deleted_at = now(), deleted_by = auth.uid() where id = p_id and deleted_at is null;
  else
    raise exception 'Tipo de registro inválido';
  end if;
end;
$$;

-- Vendedor: cria a solicitação. Admin: exclui na hora.
create or replace function public.request_deletion(p_entity_type text, p_entity_id uuid, p_reason text default null)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_client uuid;
  v_label text;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
  v_req uuid;
begin
  if not public.is_active_user() then
    raise exception 'Seu acesso ainda não foi liberado';
  end if;
  if p_entity_type = 'client' then
    select id into v_client from public.clients where id = p_entity_id and deleted_at is null;
  elsif p_entity_type = 'interaction' then
    select client_id into v_client from public.interactions where id = p_entity_id and deleted_at is null;
  elsif p_entity_type = 'sale' then
    select client_id into v_client from public.sales where id = p_entity_id and deleted_at is null;
  else
    raise exception 'Tipo de registro inválido';
  end if;
  if v_client is null or not public.can_access_client(v_client) then
    raise exception 'Registro não encontrado ou sem permissão';
  end if;

  v_label := public.entity_label(p_entity_type, p_entity_id);

  if public.is_admin() then
    -- fecha solicitações pendentes do mesmo registro
    update public.deletion_requests
       set status = 'approved', decided_by = auth.uid(), decided_at = now(),
           decision_note = 'Excluído diretamente pelo administrador'
     where entity_type = p_entity_type and entity_id = p_entity_id and status = 'pending';
    insert into public.deletion_requests
      (entity_type, entity_id, client_id, entity_label, reason, status, requested_by, decided_by, decided_at, decision_note)
    values (p_entity_type, p_entity_id, v_client, v_label, v_reason, 'approved', auth.uid(), auth.uid(), now(), 'Exclusão direta do administrador');
    perform public.soft_delete_record(p_entity_type, p_entity_id);
    perform public.log_activity('EXCLUIU', p_entity_type, p_entity_id,
      'Excluiu — ' || v_label || coalesce(' — motivo: ' || v_reason, ''));
    return 'deleted';
  end if;

  if exists (select 1 from public.deletion_requests where entity_type = p_entity_type and entity_id = p_entity_id and status = 'pending') then
    raise exception 'Já existe uma solicitação de exclusão pendente para este registro';
  end if;

  insert into public.deletion_requests (entity_type, entity_id, client_id, entity_label, reason, requested_by)
  values (p_entity_type, p_entity_id, v_client, v_label, v_reason, auth.uid())
  returning id into v_req;
  perform public.log_activity('SOLICITOU_EXCLUSAO', p_entity_type, p_entity_id,
    'Solicitou a exclusão — ' || v_label || coalesce(' — motivo: ' || v_reason, ''));
  return 'requested';
end;
$$;

create or replace function public.approve_deletion(p_request_id uuid, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
declare r public.deletion_requests%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem aprovar exclusões';
  end if;
  select * into r from public.deletion_requests where id = p_request_id for update;
  if not found or r.status <> 'pending' then
    raise exception 'Solicitação não encontrada ou já decidida';
  end if;
  update public.deletion_requests
     set status = 'approved', decided_by = auth.uid(), decided_at = now(), decision_note = nullif(trim(coalesce(p_note, '')), '')
   where id = p_request_id;
  perform public.log_activity('APROVOU_EXCLUSAO', r.entity_type, r.entity_id,
    'Aprovou a solicitação de ' || public.person_name(r.requested_by) || ' para excluir — ' || r.entity_label);
  perform public.soft_delete_record(r.entity_type, r.entity_id);
  perform public.log_activity('EXCLUIU', r.entity_type, r.entity_id,
    'Excluiu — ' || r.entity_label || ' (solicitação aprovada)');
end;
$$;

create or replace function public.reject_deletion(p_request_id uuid, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
declare r public.deletion_requests%rowtype; v_note text := nullif(trim(coalesce(p_note, '')), '');
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem recusar exclusões';
  end if;
  select * into r from public.deletion_requests where id = p_request_id for update;
  if not found or r.status <> 'pending' then
    raise exception 'Solicitação não encontrada ou já decidida';
  end if;
  update public.deletion_requests
     set status = 'rejected', decided_by = auth.uid(), decided_at = now(), decision_note = v_note
   where id = p_request_id;
  perform public.log_activity('RECUSOU_EXCLUSAO', r.entity_type, r.entity_id,
    'Recusou a solicitação de ' || public.person_name(r.requested_by) || ' para excluir — ' || r.entity_label ||
    coalesce(' — motivo: ' || v_note, ''));
end;
$$;

